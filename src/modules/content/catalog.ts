const q = (
  skill: Skill,
  id: number,
  concept: string,
  prompt: string,
  options: string[],
  correct: number,
  reason: string,
): Question => ({
  id: `${skill}-${id}`,
  skill,
  concept,
  prompt,
  options,
  correct,
  feedback: options.map(
    (_, i) => (i === correct ? "ใช่เลย! " : "ลองคิดอีกครั้ง: ") + reason,
  ),
});
